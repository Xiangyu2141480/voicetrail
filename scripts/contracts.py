"""Generate the frontend's types from the real FastAPI OpenAPI schemas."""
import argparse
import json
import tempfile
from pathlib import Path

from backend.app.config import Settings
from backend.app.main import create_app

ROOT = Path(__file__).resolve().parents[1]


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(typescript(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        properties = schema.get("properties", {})
        return "{\n" + "\n".join(
            f"  {name}{'' if name in required else '?'}: {typescript(prop)};"
            for name, prop in properties.items()) + "\n}"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as folder:
        openapi = create_app(Settings(Path(folder)), start_worker=False).openapi()
    output = "// Generated by python -m scripts.contracts; do not edit.\n"
    for name, schema in sorted(openapi["components"]["schemas"].items()):
        output += f"export type {name} = {typescript(schema)};\n\n"
    output = output.rstrip() + "\n"
    path = ROOT / "frontend/src/contracts.ts"
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit("HTTP contract differs; run python -m scripts.contracts.")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output)
        (ROOT / "docs/openapi.json").write_text(json.dumps(openapi, indent=2) + "\n")


if __name__ == "__main__":
    main()
